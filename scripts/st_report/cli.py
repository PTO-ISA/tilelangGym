#!/usr/bin/env python3
"""CLI: init | harvest | plot | plot-ipc | gaps | fill | check | export-stage-taxonomy | stage-mid --st <id>"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def _ensure_repo_on_path() -> None:
    root = Path(__file__).resolve().parents[2]
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))


def cmd_init(st: str, aims: str, design: str, refresh_aims: bool) -> int:
    from scripts.st_report.init_st import init_st

    result = init_st(st, aims=aims, design=design or "", refresh_aims=refresh_aims)
    print(f"wrote {result['arms']}")
    print(f"  spine: {result['spine']}")
    print(f"  trail: {result['trail']}")
    print(f"  analysis: {result['analysis']} ({result['analysis_action']})")
    return 0


def cmd_harvest(st: str) -> int:
    from scripts.st_report.harvest import harvest

    result = harvest(st)
    print(f"wrote {result['path']} ({result['n']} spine rows)")
    return cmd_gaps(st)


def cmd_plot(st: str, window: float) -> int:
    from scripts.st_report.plots import plot

    result = plot(st, window=window)
    print(f"plots dir: {result['out_dir']}  W={result['window']}")
    for line in result.get("generated") or []:
        print(f"  gen:   {line}")
    for line in result["wired"]:
        print(f"  wired: {line}")
    for line in result["skipped"]:
        print(f"  skip:  {line}")
    return 0


def cmd_gaps(st: str) -> int:
    from scripts.st_report.registry import gaps_path, load_arms, plots_dir, read_summary, trail_ids

    arms = load_arms(st)
    rows = read_summary(st)
    lines = [
        f"# gaps — `{st}`",
        "",
        f"Auto-generated by `python -m scripts.st_report gaps --st {st}`.",
        "Human fill only — do not invent numbers to clear these.",
        "",
    ]
    gaps: list[str] = []
    for r in rows:
        arm = r.get("arm", "")
        status = (r.get("status") or "").upper()
        if status == "TODO" or not (r.get("el_cyc") or "").strip():
            gaps.append(f"- **{arm}**: el_cyc missing / status=TODO")
        if (r.get("el_cyc") or "").strip() and not (r.get("mid_ipc_W") or "").strip():
            gaps.append(f"- **{arm}**: mid_ipc_W empty (W=20 not harvested)")
        if (r.get("el_cyc") or "").strip() and not (r.get("mid_in_el_cyc") or "").strip():
            if r.get("path") == "dsl" or arm == "simd_dsl_best":
                gaps.append(f"- **{arm}**: mid_in_el_cyc empty")
        if arm == "simt_asc_default":
            gaps.append(f"- **{arm}**: Ascend default el/cyc + T-dim + LDS/STS 32 vs 64")
    pdir = plots_dir(st)
    for arm in arms["spine"]:
        aid = arm["id"]
        art = arm.get("artifacts") if isinstance(arm.get("artifacts"), dict) else {}
        png = pdir / f"{aid}_running_ipc.png"
        if not png.is_file() and not png.is_symlink():
            if aid == "simt_asc_default" and not art:
                gaps.append(f"- **{aid}**: missing running-IPC (no Asc artifacts yet)")
            else:
                gaps.append(f"- **{aid}**: missing report/plots/{aid}_running_ipc.png")
        # log presence hint
        if art and not any(art.get(k) for k in ("popped_dump", "trace", "rolling_csv", "running_ipc_png")):
            gaps.append(f"- **{aid}**: artifacts block empty of logs/PNG paths")

    tids = trail_ids(arms)
    lines.append("## Open gaps")
    lines.append("")
    if gaps:
        seen: set[str] = set()
        for g in gaps:
            if g not in seen:
                lines.append(g)
                seen.add(g)
    else:
        lines.append("- (none)")
    lines += [
        "",
        "## Quarantined trail (must not enter ANALYSIS conclusion)",
        "",
        *[f"- `{t}`" for t in tids],
        "",
    ]
    path = gaps_path(st)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {path} ({len(gaps)} gap lines)")
    return 0


def cmd_fill(st: str, write: bool) -> int:
    from scripts.st_report.fill_analysis import fill

    result = fill(st, write=write)
    print(result["text"])
    return 0


def cmd_check(st: str) -> int:
    from scripts.st_report.check_spine import check

    result = check(st)
    for w in result["warnings"]:
        print(f"WARN: {w}")
    for e in result["errors"]:
        print(f"ERROR: {e}")
    if result["ok"]:
        print(f"OK: spine={result['spine']} trail_quarantined={result['trail']}")
        return 0
    print("FAIL")
    return 1


def cmd_selftest() -> int:
    """Synthetic fixture → PNG (proves parser/plot path without ST digs)."""
    import tempfile

    from scripts.st_report.rolling_ipc import DEFAULT_W, build_from_artifacts, write_tiny_fixture

    with tempfile.TemporaryDirectory(prefix="st_report_ipc_") as td:
        td_path = Path(td)
        fix = write_tiny_fixture(td_path / "fixture")
        out = td_path / "out" / "fixture_running_ipc.png"
        result = build_from_artifacts(
            {"trace": str(fix["trace"]), "instr_csv": str(fix["instr_csv"]), "E": 200},
            st_root=td_path,
            repo_root=td_path,
            W=DEFAULT_W,
            out_png=out,
            title="selftest running IPC",
            E=200.0,
        )
        style = result["meta"].get("plot_style")
        ok = out.is_file() and Path(result["json"]).is_file() and style == "opcode_lanes_ipc"
        print(
            f"selftest: {'PASS' if ok else 'FAIL'} png={out} "
            f"style={style} mid-med={result['meta'].get('mid_med_ipc')} "
            f"lanes={result['meta'].get('lane_opcodes')}"
        )
        return 0 if ok else 1



def cmd_export_stage_taxonomy(st: str, out: str) -> int:
    from scripts.st_report.stage_taxonomy import default_export_path, write_json

    path = Path(out) if out else default_export_path(st or None)
    wrote = write_json(path)
    print(f"wrote {wrote}")
    print("module=scripts.st_report.stage_taxonomy.STAGE_TAXONOMY")
    return 0


def cmd_stage_mid(
    st: str,
    out: str,
    window: float,
    softlib_dump: str,
    simd_dump: str,
    softlib_id: str,
    simd_id: str,
) -> int:
    """Harvest stage mid-IPC; prefer arms.yaml artifacts, else explicit dumps."""
    from scripts.st_report.registry import load_arms, st_dir
    from scripts.st_report.stage_taxonomy import harvest_stage_mid, write_json as write_tax

    specs: list[dict] = []
    # Explicit dumps win; else scan arms.yaml spine for popped_dump + path/frontend.
    if softlib_dump or simd_dump:
        if softlib_dump:
            specs.append(
                {
                    "id": softlib_id,
                    "frontend": "softlib_simt",
                    "popped_dump": softlib_dump,
                    "title": f"{st} / SoftLib SIMT — stage mid-IPC",
                }
            )
        if simd_dump:
            specs.append(
                {
                    "id": simd_id,
                    "frontend": "simd",
                    "popped_dump": simd_dump,
                    "title": f"{st} / SIMD — stage mid-IPC",
                }
            )
    else:
        try:
            arms = load_arms(st)
        except FileNotFoundError as e:
            print(f"ERROR: {e}; pass --softlib-dump/--simd-dump or add arms.yaml", file=sys.stderr)
            return 1
        for arm in arms.get("spine") or []:
            art = arm.get("artifacts") if isinstance(arm.get("artifacts"), dict) else {}
            dump = art.get("popped_dump")
            if not dump:
                continue
            path_kind = (arm.get("path") or arm.get("role") or arm.get("id") or "").lower()
            if "softlib" in path_kind or (
                "simt" in path_kind and "asc" not in path_kind and "simd" not in path_kind
            ):
                fe = "softlib_simt"
            elif "simd" in path_kind or "dsl" in path_kind or "vmi" in path_kind:
                fe = "simd"
            else:
                # skip simt_asc by default for stage-mid dual-arm SoT
                continue
            root = st_dir(st)
            dump_path = Path(dump)
            if not dump_path.is_file():
                cand = root / dump
                if cand.is_file():
                    dump_path = cand
            specs.append(
                {
                    "id": arm["id"],
                    "frontend": fe,
                    "popped_dump": str(dump_path),
                    "title": arm.get("label") or arm["id"],
                }
            )
    if not specs:
        print(
            "ERROR: no SoftLib/SIMD dumps resolved; pass --softlib-dump/--simd-dump",
            file=sys.stderr,
        )
        return 1

    doc = harvest_stage_mid(specs, W=window)
    out_path = Path(out) if out else (st_dir(st) / "plots" / f"{st}_stage_mid_ipc.json")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    # Always refresh co-located taxonomy export
    tax = write_tax(st_dir(st) / "plots" / "stage_taxonomy.json")
    print(f"wrote {out_path} arms={list(doc.get('arms') or {})}")
    print(f"taxonomy {tax}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="st_report", description="tilelangGym ST report harness")
    sub = p.add_subparsers(dest="cmd", required=True)

    def add_st(sp: argparse.ArgumentParser) -> None:
        sp.add_argument("--st", required=True, help="ST id under benches/ (e.g. sv5)")

    sp_init = sub.add_parser("init", help="write arms.yaml (+ ANALYSIS stub if missing) from Aims/design")
    add_st(sp_init)
    sp_init.add_argument("--aims", required=True, help="author-confirmed Aims (required)")
    sp_init.add_argument(
        "--design",
        default="",
        help="optional design prompt (kernels, E/TILE/T or VL/G, arm hints)",
    )
    sp_init.add_argument(
        "--refresh-aims",
        action="store_true",
        help="if ANALYSIS.md exists, refresh ## 1. Aims only (default: leave prose alone)",
    )

    for name in ("harvest", "gaps", "check"):
        sp = sub.add_parser(name)
        add_st(sp)

    for name, help_ in (
        ("plot", "generate or wire running-IPC PNGs for spine arms"),
        ("plot-ipc", "alias of plot (running-IPC / VF-log analysis)"),
    ):
        sp = sub.add_parser(name, help=help_)
        add_st(sp)
        sp.add_argument(
            "--window",
            type=float,
            default=20.0,
            help="rolling IPC window W in cycles (default 20; convention (t−W,t])",
        )

    sp_fill = sub.add_parser("fill")
    add_st(sp_fill)
    sp_fill.add_argument(
        "--dry-run",
        action="store_true",
        default=True,
        help="print stub tables only (default)",
    )
    sp_fill.add_argument(
        "--write",
        action="store_true",
        help="refused in milestone 1 unless explicitly allowed later",
    )

    sp_tax = sub.add_parser(
        "export-stage-taxonomy",
        help="write STAGE_TAXONOMY JSON (SoT for §8.1/§8.2/staged PR9)",
    )
    sp_tax.add_argument("--st", default="", help="optional ST id → benches/<st>/plots/stage_taxonomy.json")
    sp_tax.add_argument(
        "-o",
        "--out",
        default="",
        help="output path (default: benches/<st>/plots/stage_taxonomy.json or scripts/st_report/stage_taxonomy.json)",
    )

    sp_sm = sub.add_parser(
        "stage-mid",
        help="harvest stage mid-IPC JSON from dumps using STAGE_TAXONOMY defining windows",
    )
    sp_sm.add_argument("--st", required=True)
    sp_sm.add_argument(
        "-o",
        "--out",
        default="",
        help="output JSON (default: benches/<st>/plots/<st>_stage_mid_ipc.json)",
    )
    sp_sm.add_argument("--window", type=float, default=20.0)
    sp_sm.add_argument(
        "--softlib-dump",
        default="",
        help="SoftLib SIMT popped dump (overrides arms.yaml artifacts)",
    )
    sp_sm.add_argument(
        "--simd-dump",
        default="",
        help="SIMD popped dump (overrides arms.yaml artifacts)",
    )
    sp_sm.add_argument(
        "--softlib-id",
        default="softlib_simt",
        help="arm id key in output JSON",
    )
    sp_sm.add_argument(
        "--simd-id",
        default="simd",
        help="arm id key in output JSON",
    )

    sub.add_parser("selftest-ipc", help="synthetic chrome fixture → PNG (no ST dig)")
    return p


def main(argv: list[str] | None = None) -> int:
    _ensure_repo_on_path()
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.cmd == "selftest-ipc":
        return cmd_selftest()
    if args.cmd == "export-stage-taxonomy":
        return cmd_export_stage_taxonomy(getattr(args, "st", "") or "", getattr(args, "out", "") or "")
    st = args.st
    if args.cmd == "init":
        return cmd_init(
            st,
            aims=args.aims,
            design=getattr(args, "design", "") or "",
            refresh_aims=bool(getattr(args, "refresh_aims", False)),
        )
    if args.cmd == "harvest":
        return cmd_harvest(st)
    if args.cmd in ("plot", "plot-ipc"):
        return cmd_plot(st, window=float(getattr(args, "window", 20.0)))
    if args.cmd == "gaps":
        return cmd_gaps(st)
    if args.cmd == "fill":
        write = bool(getattr(args, "write", False))
        return cmd_fill(st, write=write)
    if args.cmd == "check":
        return cmd_check(st)
    if args.cmd == "stage-mid":
        return cmd_stage_mid(
            st,
            out=getattr(args, "out", "") or "",
            window=float(getattr(args, "window", 20.0)),
            softlib_dump=getattr(args, "softlib_dump", "") or "",
            simd_dump=getattr(args, "simd_dump", "") or "",
            softlib_id=getattr(args, "softlib_id", "softlib_simt") or "softlib_simt",
            simd_id=getattr(args, "simd_id", "simd") or "simd",
        )
    parser.error(f"unknown cmd {args.cmd}")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
